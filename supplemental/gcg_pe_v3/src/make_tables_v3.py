"""One command, every table and figure, all from the per-attempt log.

    python -m src.make_tables_v3 runs/x/attempts_v3.jsonl --outdir tables/

The Open Science section claims "no number is transcribed by hand, and re-running
the script reproduces them exactly". That claim is currently false: two of the
three figure scripts hard-code every rate and one has no log-reading path at all.
This module makes the claim true. Run it twice and the outputs are byte
identical; if a number is not in the log it does not appear in a table.

Emits, with one declared interval method throughout:
  tab_power.tex         what a measured floor permits (Prop. power)
  tab_main.tex          per-model rates, with n_persons/n_targets/n_attempts
  tab_spectrum.tex      the probe spectrum, with n and an interval per row
  tab_perfield.tex      every rate split by field
  tab_2x2.tex           the four cells, placebo contrast and DiD
  tab_feasibility.tex   the operating-point feasibility table
  fig_capacity.pdf      the measured operating characteristic
  numbers.json          every scalar the prose quotes, keyed by name
"""
