INTERVAL_NOTE = ("All intervals are 95\\% person-clustered bootstrap, paired "
                 "across arms where the design is matched; boundary cells use a "
                 "person-level Clopper--Pearson bound, which is stated rather "
                 "than an unexplained effective sample size.")


def _u(g, by="person_id"):
    return [list(v["exact_match"].astype(int)) for _, v in g.groupby(by)]


def _units_map(g, by="person_id"):
    return {pid: list(v["exact_match"].astype(int)) for pid, v in g.groupby(by)}


def _pct(x, d=1):
    return "--" if x is None or not np.isfinite(x) else f"{100*x:.{d}f}"


def _tex_table(caption: str, label: str, header: List[str], rows: List[List[str]],
               colspec: Optional[str] = None, note: str = "") -> str:
    colspec = colspec or ("l" + "c" * (len(header) - 1))
    body = "\n".join(" & ".join(r) + " \\\\" for r in rows)
    return (f"% generated by src.make_tables_v3 -- do not edit by hand\n"
            f"\\begin{{table}}[t]\n\\centering\n\\caption{{{caption} {note}}}\n"
            f"\\label{{{label}}}\n\\footnotesize\n"
            f"\\setlength{{\\tabcolsep}}{{4pt}}\n"
            f"\\begin{{tabular}}{{@{{}}{colspec}@{{}}}}\n\\toprule\n"
            + " & ".join(header) + " \\\\\n\\midrule\n" + body
            + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")


